import { describe, expect, it } from 'vitest'
import type { Dataset, Workspace } from '../types'
import { matlabScript, matlabScriptName, matlabString, SERIES_COLORS, type MatlabExportOptions } from './matlab'
import { MATLAB_LIBRARY_FUNCTIONS, matlabLibrary } from './matlabLibrary'
import { derivedChannel, fileChannel, makeDataset, makeWorkspace, sampleDataset } from './testFixtures'

const ALL = { points: true, xy: true, time: true, modes: true }

function script(patch: Partial<MatlabExportOptions> = {}, ds: Dataset = sampleDataset(), ws: Workspace = makeWorkspace()) {
  return matlabScript({ ds, ws, include: ALL, view: null, modeRows: [1, 5], ...patch })
}

/** The script body (everything before the local functions). */
function body(text: string): string {
  return text.slice(0, text.indexOf('%% Local functions'))
}

/** Names of the local functions defined in a script. */
function definedFunctions(text: string): string[] {
  return [...text.matchAll(/^function (?:\[[^\]]*\]|\w+) = (\w+)\(|^function (\w+)\(/gm)].map((m) => m[1] ?? m[2])
}

describe('matlabString', () => {
  it('doubles single quotes and keeps plain text readable', () => {
    expect(matlabString("Pilot's pick")).toBe("'Pilot''s pick'")
    expect(matlabString('')).toBe("''")
    expect(matlabString("''")).toBe("''''''")
  })

  it('puts line breaks and control characters on one line', () => {
    expect(matlabString('two\nlines\r\n\there')).toBe("'two lines here'")
  })

  it('writes non-ASCII characters as char codes, independent of the file encoding', () => {
    expect(matlabString('lb\u00b7ft')).toBe("['lb' char(183) 'ft']")
    expect(matlabString('\u00b0')).toBe('char(176)')
    expect(matlabString('\u{1F600}!')).toBe("[char(55357) char(56832) '!']")
  })
})

describe('matlabScriptName', () => {
  it('is a valid MATLAB script name (letters, digits, underscores, max 63 + .m)', () => {
    expect(matlabScriptName('Data_performance run 1.txt')).toBe('xpp_Data_performance_run_1.m')
    expect(matlabScriptName('Demo flight (synthetic).txt')).toBe('xpp_Demo_flight_synthetic.m')
    expect(matlabScriptName('Vol élevé.csv')).toBe('xpp_Vol_eleve.m')
    expect(matlabScriptName('...')).toBe('xpp_export.m')
    const long = matlabScriptName(`${'a'.repeat(100)}.txt`)
    expect(long).toMatch(/^xpp_a+\.m$/)
    expect(long.length).toBe(63 + 2)
  })
})

describe('matlabScript', () => {
  it('starts with a header comment: generator, app URL, date, source file and size, how to use', () => {
    const text = script({ appUrl: 'https://example.org/xpp/' })
    const header = text.slice(0, text.indexOf('%% 1. Settings'))
    expect(header.startsWith('%% X-Plane Plotter export: Data.txt\n')).toBe(true)
    expect(header).toMatch(/% Generated by X-Plane Plotter \(https:\/\/example\.org\/xpp\/\) on \d{4}-\d\d-\d\d \d\d:\d\d UTC\./)
    expect(header).toContain('% Source log: Data.txt, 6 rows x 5 columns (12.3 MB), X-Plane Data.txt format.')
    expect(header).toContain("run('xpp_Data.m')")
    expect(header).toContain('out/test_points.csv')
    expect(header).toContain('R2021a')
    expect(header.split('\n').every((line) => line === '' || line.startsWith('%'))).toBe(true)
  })

  it('has the settings block at the top', () => {
    const text = script({ dataFile: "C:\\logs\\Bob's Data.txt" })
    const settings = text.slice(text.indexOf('%% 1. Settings'), text.indexOf('%% 2.'))
    expect(settings).toContain("dataFile = 'C:\\logs\\Bob''s Data.txt';")
    expect(settings).toContain("outDir = fullfile(fileparts(mfilename('fullpath')), 'out');")
    expect(settings).toMatch(/^showFigures = true; +%/m)
  })

  it('reads the log with readXPlaneLog, a local function at the end of the file', () => {
    const text = script()
    expect(text).toContain('[D, logNames] = readXPlaneLog(dataFile);')
    const definition = text.indexOf('function [D, names] = readXPlaneLog(file)')
    expect(definition).toBeGreaterThan(text.indexOf('%% Local functions'))
    // The script's last statement comes before the local functions (MATLAB requires them at the end of a script).
    const tail = text.slice(text.indexOf('%% Local functions'))
    expect(tail.split('\n').find((line, i) => i > 0 && line.trim() !== '')).toMatch(/^function /)
    expect(text.indexOf("fprintf('\\nDone. Outputs are in")).toBeLessThan(text.indexOf('%% Local functions'))
    expect(text.trimEnd().endsWith('end')).toBe(true)
    // Fast path of the reader: whole-file read, one sscanf.
    expect(tail).toContain('fileread(file)')
    expect(tail).toContain("sscanf(joined, '%f')")
    expect(tail).toContain("count(B, delim)")
  })

  it('maps channel ids to columns by token and occurrence, escaping tokens', () => {
    const text = body(script())
    expect(text).toContain("col = @(token, occurrence) xppColumn(logNames, token, occurrence);")
    expect(text).toContain("D(:, col('_Vind,_kias', 1))")
    expect(text).toContain("D(:, col('elev1,__deg', 2))")
  })

  it('re-creates elapsed time from the app time source (or row numbers without one)', () => {
    expect(body(script())).toContain("[el, dtMedian, segStart] = xppElapsed(D(:, col('_totl,_time', 1)));")
    const ds = sampleDataset()
    const noTime = script({}, { ...ds, timeSourceId: null })
    expect(body(noTime)).toContain("el = (0:nRows - 1)';")
    expect(noTime).not.toContain('function [el, dt, segStart] = xppElapsed(t)')
  })

  it('writes test points as 1-based inclusive rows with the app elapsed times, names escaped', () => {
    const ws = makeWorkspace({
      points: [
        { id: 'a', name: "Pilot's pick", groupId: 'g1', start: 0, end: 3 },
        { id: 'b', name: 'line\nbreak', groupId: 'g2', start: 4, end: 6, hidden: true },
      ],
    })
    const text = body(script({}, sampleDataset(), ws))
    expect(text).toContain("pointName = {'Pilot''s pick'; 'line break'};")
    expect(text).toContain("groupName = {'CG fwd'; 'CG \"aft\", test'};")
    expect(text).toContain('groupSlot = [1; 4];')
    expect(text).toContain('pointGroup = [1; 2];')
    expect(text).toContain('pointHidden = [false; true];')
    expect(text).toMatch(/^ {4} {3}1 {4}3 +0 +1 +% Pilot's pick$/m)
    expect(text).toMatch(/^ {4} {3}5 {4}6 +2 +2\.5 +% line break$/m)
    expect(text).toContain('xppRows(el, pointWindow(iPoint, 1)')
  })

  it('builds the test-point table from the tracked channels', () => {
    const text = body(script())
    expect(text).toContain("'Vind_kias', D(:, col('_Vind,_kias', 1)), 'KIAS [kt]'")
    expect(text).toContain("'elev1_deg_2', D(:, col('elev1,__deg', 2)), 'elev1 (2) [deg]'")
    expect(text).toContain("writetable(T, fullfile(outDir, 'test_points.csv'));")
    expect(text).toContain('disp(T);')
  })

  it('includes and leaves out sections and helpers by the include flags', () => {
    const none = script({ include: { points: false, xy: false, time: false, modes: false } })
    expect(none).not.toContain('test_points.csv')
    expect(none).not.toContain('seriesColors')
    expect(definedFunctions(none)).not.toContain('xppFigure')
    expect(definedFunctions(none)).toContain('readXPlaneLog')

    const all = script()
    expect(body(all)).toMatch(/^%% \d+\. Test-point table -> out\/test_points\.csv$/m)
    expect(body(all)).toContain("xppExport(fig, fullfile(outDir, 'xy'), showFigures);")
    expect(body(all)).toContain("xppExport(fig, fullfile(outDir, 'time_history'), showFigures);")
    expect(body(all)).toContain("xppExport(fig, fullfile(outDir, 'mode_fit'), showFigures);")
    // Both mode models are defined, so modeCfg.model can be switched in MATLAB.
    expect(definedFunctions(all)).toEqual(
      expect.arrayContaining(['xppFitOscillation', 'xppFitFirstOrder', 'xppPolyFit', 'xppStats', 'xppRows']),
    )

    const onlyTime = script({ include: { points: false, xy: false, time: true, modes: false } })
    expect(onlyTime).toContain('time_history')
    expect(onlyTime).not.toContain("'xy')")
    expect(onlyTime).not.toContain('pointWindow')
  })

  it('defines every local function it calls, exactly once', () => {
    const ws = makeWorkspace({
      modes: { channelId: '_Vind,_kias', source: 'view', model: 'first-order', detrend: 'none' },
    })
    for (const text of [script(), script({}, sampleDataset(), ws)]) {
      const defined = definedFunctions(text)
      expect(new Set(defined).size).toBe(defined.length)
      const called = new Set([...text.matchAll(/\b(xpp[A-Z]\w*|readXPlaneLog)\(/g)].map((m) => m[1]))
      for (const name of called) expect(defined, name).toContain(name)
    }
  })

  it('writes the X-Y settings and colours', () => {
    const text = body(script())
    expect(text).toContain("xy.x = D(:, col('elev1,__deg', 1));")
    expect(text).toContain("xy.source = 'points';")
    expect(text).toContain('xy.fitDegree = 1;')
    expect(text).toContain("xy.fitTarget = 'means';")
    expect(text).toContain("xy.xLabel = 'elev1 [deg]';")
    for (const c of SERIES_COLORS) expect(text).toContain(c.hex)
    expect(text).toContain('     42 120 214   % 1 #2a78d6 blue')
    // Every group is plotted unless the X–Y tab picked some.
    expect(text).toContain('xy.useGroup = [true; true];')
    expect(text).toContain('if ~xy.useGroup(iGroup)')
  })

  it('plots only the test-point groups chosen in the X–Y tab', () => {
    const ws = makeWorkspace()
    const text = body(script({}, sampleDataset(), { ...ws, xy: { ...ws.xy, groups: ['g2'] } }))
    expect(text).toContain('xy.useGroup = [false; true];')
  })

  it('uses the zoom range for "view" with its 1-based rows', () => {
    const ws = makeWorkspace()
    const text = body(script({ view: [1, 4] }, sampleDataset(), { ...ws, xy: { ...ws.xy, source: 'view' } }))
    expect(text).toContain("xy.viewRows = xppRows(el, 2, 4, 0.5, 1.5, 'the app''s zoom range');")
    expect(text).toContain("thRows = xppRows(el, 2, 4, 0.5, 1.5, 'the app''s zoom range');")
    // Without a zoom range, "view" is the whole log; the test points are still defined (xy.source can be switched).
    const whole = body(script({ view: null }, sampleDataset(), { ...ws, xy: { ...ws.xy, source: 'all' } }))
    expect(whole).toContain("xy.viewRows = (1:nRows)';")
    expect(whole).toContain('pointWindow = [')
  })

  it('fits the mode on the selection rows, or on a test point', () => {
    expect(body(script())).toContain("modeCfg.rows = xppRows(el, 2, 5, 0.5, 2, 'the app''s selection');")
    const ws = makeWorkspace({ modes: { channelId: '_Vind,_kias', source: 'point:t2', model: 'first-order', detrend: 'none' } })
    const text = body(script({ modeRows: null }, sampleDataset(), ws))
    expect(text).toContain("modeCfg.rows = xppRows(el, 3, 6, 1, 2.5, 'test point \"=SUM(A1)\"');")
    expect(text).toContain("modeCfg.model = 'first-order';")
    const noRows = body(script({ modeRows: null }))
    expect(noRows).toContain("fprintf('%s\\n', 'Mode fit skipped: no rows.');")
  })

  it('re-computes formula channels before they are used, and NaNs those it cannot translate', () => {
    const ds = sampleDataset()
    const broken = derivedChannel('broken', 'broken', '', 'unknown_thing * 2', [1, 1, 1, 1, 1, 1])
    const withBroken = { ...ds, channels: [...ds.channels, broken] }
    const ws = makeWorkspace({ tracked: ['fx:q', 'fx:broken'] })
    const text = script({}, withBroken, ws)
    const main = body(text)
    expect(main).toContain("fx_q = (D(:, col('_Vind,_kias', 1)) .* 2) + zeros(nRows, 1);")
    expect(main.indexOf('fx_q =')).toBeLessThan(main.indexOf("'q', fx_q, 'q [Pa]'"))
    expect(main).toContain('fx_broken = NaN(nRows, 1);')
    expect(main).toContain("warning('xpp:formula'")
    expect(text).toContain('formula channel "broken" could not be translated (unknown channel "unknown_thing")')
  })

  it('never leaks undefined, [object Object] or NaN where numbers are expected', () => {
    const ds = sampleDataset()
    const text = script({ view: [0, 6] }, ds)
    expect(text).not.toContain('undefined')
    expect(text).not.toContain('[object Object]')
    const numbers = body(text)
      .split('\n')
      .filter((line) => /xppRows\(el, |^ {4} +\d+ +\d+ /.test(line))
    expect(numbers.length).toBeGreaterThan(2)
    for (const line of numbers) expect(line).not.toMatch(/\bNaN\b|Infinity/)
  })

  it('handles a dataset without points, panels or channels to plot', () => {
    const ds = makeDataset([fileChannel('_totl,_time', 1, 0, [0, 1, 2], 'Sim time', 's')], [0, 1, 2])
    const ws = makeWorkspace({
      points: [],
      panels: [],
      tracked: [],
      xy: { ...makeWorkspace().xy, x: null, ys: [] },
      modes: { channelId: null, source: 'selection', model: 'oscillation', detrend: 'linear' },
    })
    const text = script({}, ds, ws)
    expect(text).toContain("fprintf('No test points: out/test_points.csv was not written.\\n');")
    expect(text).toContain("'X-Y plot skipped: no X or Y channel was chosen in the app.'")
    expect(text).toContain("'Time histories skipped: no panels.'")
    expect(text).toContain("'Mode fit skipped: no channel chosen.'")
    expect(text).not.toContain('seriesColors')
  })
})

describe('matlabLibrary', () => {
  it('returns each function once with its dependencies, in library order', () => {
    const lines = matlabLibrary(['xppPolyFit', 'xppPolyFit'])
    const names = definedFunctions(lines.join('\n'))
    expect(names).toEqual(['xppPolyFit', 'xppUnscale', 'xppPolyText'])
    expect(lines[0]).toBe('')
  })

  it('knows the reader and its helpers', () => {
    const names = definedFunctions(matlabLibrary(['readXPlaneLog']).join('\n'))
    expect(names[0]).toBe('readXPlaneLog')
    expect(names).toEqual(expect.arrayContaining(['xppParseLine', 'xppSplitCells', 'xppCellValues', 'xppNormalize', 'xppNames']))
    expect(MATLAB_LIBRARY_FUNCTIONS).toContain('xppElapsed')
    expect(() => matlabLibrary(['nope'])).toThrow('unknown function nope')
  })
})
